import Foundation

/// 3級アプリ・2級アプリで共通の固定値。
///
/// 級によって変わる値（アプリ名・バンドルID・課金プロダクトID・試験制度の数値）は
/// `AppFlavor` が持つ。両者を1つの型に混ぜると、級を増やしたときに
/// 「どれが共通でどれが級ごとか」が読み取れなくなる。
enum AppConfig {

    // MARK: - 試験

    /// 同梱する問題データ（拡張子を除いたファイル名）。級ごとに中身が違うが、
    /// ファイル名は揃える（ターゲットごとに別のファイルをバンドルへ入れる）
    static let seedResourceName = "question_master_seed"

    // MARK: - 権利表記

    /// FP技能検定は国家検定であり、日本FP協会ときんざい（金融財政事情研究会）が
    /// 指定試験機関として実施している。提携していると誤解させないため、アプリ内に常設する。
    static let trademarkNotice = """
    FP技能検定は厚生労働大臣が指定した指定試験機関（NPO法人 日本FP協会、\
    一般社団法人 金融財政事情研究会）が実施する国家検定です。\
    本アプリはこれらの団体が承認・許諾したものではありません。\
    出題内容は公開されている試験範囲に基づく独自作成の問題です。
    """

    /// 金融商品・税制を扱うため、個別の助言と受け取られないことを明示する。
    /// 教育目的であることを書いておかないと、App Review でも金融サービスとして扱われうる。
    static let disclaimer = """
    本アプリは試験対策の学習を目的としたものであり、個別の金融商品の勧誘、\
    投資助言、税務相談を行うものではありません。実際の判断は必ず有資格者にご相談ください。
    """

    /// 法令・税制は毎年改正される。どの年度基準で作問したかを常に見せる。
    /// FP技能検定は毎年9月〜翌年5月の試験が「前年10月1日時点の法令」に基づくため、
    /// 基準日を書かないと利用者が古い数値を覚えたまま受験することになる。
    static let lawBasisNotice = """
    問題は法令基準日時点の制度に基づいています。基準日より後の改正は反映されていません。
    """
}
